import { ParsedSpatialProgramIntent } from './nlp_spatial_parser';
import { OneLexer } from '../../src/one/oneLexer';
import { OneParser } from '../../src/one/oneParser';
import { OneCompiler, ExecutableCubiOAST } from '../../src/one/oneCompiler';

export interface NLPEmissionResult {
  generatedSourceCode: string;
  compiledAst: ExecutableCubiOAST;
  nodesCount: number;
  channelsCount: number;
  peakRssBudgetMb: number;
}

export class SpatialASTEmitter {
  /**
   * Generates formatted ONE Language source code from structured intent.
   */
  public emitSourceCode(intent: ParsedSpatialProgramIntent): string {
    const lines: string[] = [];

    lines.push('// =======================================================');
    lines.push(`// ONE LANGUAGE PROGRAM (Generated by one-nlp Compiler)`);
    lines.push(`// Language: ${intent.languageDetected} | Confidence: ${(intent.confidenceScore * 100).toFixed(1)}%`);
    lines.push('// =======================================================');
    lines.push('');
    lines.push(`rss_max = ${intent.rssMaxMb};`);
    lines.push(`@assert_rss(${intent.assertRssMb});`);
    lines.push(`@actuation_lock(true);`);
    lines.push('');

    // Emit Nodes
    for (const node of intent.nodes) {
      lines.push(`node ${node.nodeId} {`);
      lines.push(`  @Space(${node.coordinate[0]}, ${node.coordinate[1]}, ${node.coordinate[2]});`);
      lines.push(`  @memview(${node.memViewMb});`);
      lines.push(`  checkpoint ${node.nodeId.toLowerCase()}_init;`);
      lines.push('}');
      lines.push('');
    }

    // Emit Channels
    for (const ch of intent.channels) {
      lines.push(`channel ${ch.channelName} {`);
      lines.push(`  stream ${ch.sourceNode} -> ${ch.targetNode} : ${ch.bufferMb};`);
      lines.push(`  @gossip(${ch.harmonicPriority});`);
      lines.push('}');
      lines.push('');
    }

    // Emit Seal
    lines.push(`seal "${intent.sealFilename}";`);
    lines.push('');

    return lines.join('\n');
  }

  /**
   * Translates natural language prompt directly into compiled CubiO AST bytecode.
   */
  public compilePromptToAST(intent: ParsedSpatialProgramIntent): NLPEmissionResult {
    const sourceCode = this.emitSourceCode(intent);

    const lexer = new OneLexer(sourceCode);
    const tokens = lexer.tokenize();
    const parser = new OneParser(tokens);
    const ast = parser.parse();
    const compiler = new OneCompiler(ast);
    const compiledAst = compiler.compile();

    return {
      generatedSourceCode: sourceCode,
      compiledAst,
      nodesCount: intent.nodes.length,
      channelsCount: intent.channels.length,
      peakRssBudgetMb: intent.rssMaxMb,
    };
  }
}
